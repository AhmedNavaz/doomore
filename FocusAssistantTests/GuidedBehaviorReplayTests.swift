    private func replay(touchMouseOnReturn: Bool) -> [(phase: String, snapshot: BehaviorSnapshot)] {
        var estimator = ActivityEstimator()
        var engine = BehaviorEngine(rules: .legacyTimings, startTime: 0)
        let context = WorkContextSnapshot(monitoringEnabled: true, cameraAvailable: true,
                                          config: WorkContextConfig(mode: .manualWork))
        var result: [(String, BehaviorSnapshot)] = []
        var touchedAt: Double?
        for (t, phase, pitch, yaw, eyes, faceY, person, key, ptr) in Self.run {
            var vision = VisionSignals()
            vision.faceCount = 1
            vision.head = HeadPose(pitch: pitch, yaw: yaw, roll: 0)
            vision.eyeOpenness = eyes
            vision.faceCenterY = faceY
            vision.personCoverage = person
            var input = InputIdle(keyboard: key, pointer: ptr)
            if touchMouseOnReturn && phase == "return-screen" {
                // The new protocol asks for a touch of the mouse when the phone goes down.
                if touchedAt == nil { touchedAt = t }
                input.pointer = min(ptr, max(0, t - (touchedAt ?? t)))
            } else if let touched = touchedAt {
                input.pointer = min(ptr, t - touched)
            }
            let snapshot = SignalSnapshot(time: t, vision: vision, input: input)
            let estimate = estimator.update(snapshot)
            let behavior = engine.step(context: context, evidence: BehaviorEvidence(snapshot: snapshot, estimate: estimate))
            result.append((phase, behavior))
        }
        return result
    }

    func testTheHighPhoneRunNowGetsAnIdleAtDeskReminderDuringSustainedUse() {
        let steps = replay(touchMouseOnReturn: false)
        let reminders = steps.filter { $0.snapshot.pendingIntervention != nil }
        XCTAssertEqual(reminders.count, 1)
        XCTAssertEqual(reminders.first?.phase, "sustained-phone")
        XCTAssertEqual(reminders.first?.snapshot.pendingIntervention?.kind, .idleAtDesk)
        XCTAssertLessThan(steps.map(\.snapshot.evidenceDuration).max() ?? 0, 45, "the posture rule alone still misses this run")
    }

    func testWithAMouseTouchOnReturnTheSustainedStepAloneNeedsTheLongerPhase() {
        // The logged sustained step lasted 65 s, shorter than the rule's 10 s + 90 s, so the reminder
        // cannot come inside it once the quick reply no longer carries over. The protocol now runs 110 s.
        let steps = replay(touchMouseOnReturn: true)
        XCTAssertTrue(steps.allSatisfy { $0.snapshot.pendingIntervention == nil })
        let sustained = steps.filter { $0.phase == "sustained-phone" }.map(\.snapshot)
        let last = sustained.last
        XCTAssertGreaterThan(last?.idleStretchCueShare ?? 0, 0.5, "cues showed for most of the sustained step")
        let quick = steps.filter { $0.phase != "sustained-phone" && $0.phase != "recover" }
        XCTAssertTrue(quick.allSatisfy { $0.snapshot.pendingIntervention == nil })
    }
